function markOf(name: string) {
  if (name.startsWith("@assistant-ui/")) return "assistant-ui";
  if (name.startsWith("@lexical/")) return "lexical";
  return MARKS[name];
}

/** The mark of the project a package belongs to, or a plain package icon. */
export function PackageIcon({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  const mark = markOf(name);
  const path = mark && PATHS[mark];
  const mask = mark && MASKS[mark];

  if (mark === "vercel")
    return <VercelIcon aria-hidden className={className} />;
  if (mark && path)
    return (
      <svg
        aria-hidden
        viewBox={VIEW_BOXES[mark] ?? "0 0 24 24"}
        fill="currentColor"
        className={className}
      >
        <path d={path} />
      </svg>
    );
  if (mask)
    return (
      <span
        aria-hidden
        className={cn("block bg-current", className)}
        style={{
          maskImage: `url(${mask})`,
          maskSize: "contain",
          maskPosition: "center",
          maskRepeat: "no-repeat",
        }}
      />
    );
  return <Package aria-hidden className={cn("opacity-50", className)} />;
}
