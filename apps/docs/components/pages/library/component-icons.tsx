/** The id a component's icon is kept under. */
export const componentIconId = (link: Pick<LibraryLink, "id" | "href">) =>
  link.id ?? link.href;

/** A component's icon; `fallback` stands in for an item that has none. */
export function ComponentIcon({
  id,
  fallback = null,
  className,
}: {
  id: string;
  fallback?: ReactNode;
  className?: string;
}) {
  const Icon = ICONS[id];
  return Icon ? (
    <Icon
      aria-hidden
      strokeWidth={1.5}
      className={cn("text-muted-foreground size-4 shrink-0", className)}
    />
  ) : (
    fallback
  );
}
