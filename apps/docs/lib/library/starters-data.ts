export const STARTER_INTEGRATIONS = [
  "Assistant Cloud",
  "Clerk",
  "LangSmith",
  "MCP",
  "LiveKit",
  "ElevenLabs",
] as const;

export type StarterIntegration = (typeof STARTER_INTEGRATIONS)[number];

export type Starter = {
  name: string;
  label: string;
  description: string;
  kind: StarterKind;
  framework: StarterFramework;
  /** The library or protocol the app talks to its model through, when it has one. */
  runtime?: StarterRuntime;
  /** Third-party services it connects to beyond its runtime. */
  integrations?: readonly StarterIntegration[];
  /** Variables its `.env.example` lists. */
  env: readonly string[];
  /** assistant-ui registry items `create` installs, following each item's registry dependencies. */
  components: readonly string[];
  /** shadcn/ui items `create` installs, following each item's registry dependencies. */
  uiComponents: readonly string[];
  /** The component, hook, and lib files those items write into the project. */
  files: readonly string[];
  /** npm packages the project ends up with: its `package.json` plus what the registry items add. */
  dependencies: readonly string[];
  /** The components ship inside the starter instead of being installed from the registry. */
  componentsIncluded?: true;
  /** The `package.json` script that starts it locally, when it is not `dev`. */
  devScript?: string;
  /** A screenshot of the app running, from public/screenshot/examples. */
  image?: string;
  /** Screenshots of the app in each color mode, in the order a card cycles through them. */
  screenshots?: {
    light: readonly string[];
    dark: readonly string[];
  };
  /** Phone-width (390 by 844) screenshots in each color mode, in the same order as `screenshots`. */
  phoneScreenshots?: {
    light: readonly string[];
    dark: readonly string[];
  };
};

